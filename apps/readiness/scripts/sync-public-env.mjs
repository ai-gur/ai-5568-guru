/**
 * Copies the NEXT_PUBLIC_* values from the monorepo's single .env.local into
 * one Next can read.
 *
 * Server code reads the root file at runtime through lib/env.ts, but
 * NEXT_PUBLIC_* is different: Next inlines those into the client bundle at
 * build time, so they have to be present in the app directory before the build
 * starts. Rather than keep a second hand-maintained file — two truths, and the
 * one you forget is always the one that matters — the derived file is
 * regenerated on every build and gitignored.
 *
 * Only NEXT_PUBLIC_ keys are copied. Anything else would be written into a file
 * whose whole purpose is to reach the browser.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../.env.local');
const target = resolve(here, '../.env.local');

let text;
try {
  text = readFileSync(source, 'utf8');
} catch {
  // Absent in CI and in production, where the platform sets real variables.
  process.exit(0);
}

const lines = text
  .split(/\r?\n/)
  .filter((line) => /^\s*NEXT_PUBLIC_[A-Z0-9_]+\s*=/.test(line))
  .map((line) => line.trim());

writeFileSync(
  target,
  ['# GENERATED by scripts/sync-public-env.mjs — do not edit.', '# Source of truth: ../../.env.local', ...lines, ''].join('\n'),
  'utf8',
);

console.log(`sync-public-env: ${lines.length} public variables`);
